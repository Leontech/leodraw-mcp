func createQR(ctx context.Context, d *Deps, a *qrArgs) (*mcp.Result, error) {
	if a.Size <= 0 {
		return nil, errors.New("size must be greater than 0")
	}
	lvl, err := qr.ParseLevel(a.Level)
	if err != nil {
		return nil, err
	}
	quiet := 4
	if a.Quiet != nil {
		quiet = *a.Quiet
	}
	col := colors.Color{Model: colors.RGB}
	if a.Color != "" {
		if col, err = colors.Parse(a.Color); err != nil {
			return nil, err
		}
	}
	code, err := qr.Encode(a.Text, qr.Options{Level: lvl, Mask: -1})
	if err != nil {
		return nil, err
	}
	n := code.Size + 2*quiet
	module := a.Size / float64(n)
	if module < 0.2 {
		return nil, fmt.Errorf("the code needs %d×%d modules – %g mm gives %.2f mm per module, too small to scan; make it bigger", n, n, a.Size, module)
	}
	// One curve via SVG import: thousands of COM calls are avoided.
	svg := fmt.Sprintf(`<svg xmlns="http://www.w3.org/2000/svg" width="%gmm" height="%gmm" viewBox="0 0 %d %d">`+
		`<path fill="#000" fill-rule="nonzero" d="%s"/></svg>`, a.Size, a.Size, n, n, code.PathData(quiet))
	dir := filepath.Join(os.TempDir(), "LeoDraw")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, err
	}
	file := filepath.Join(dir, fmt.Sprintf("qr-%d.svg", time.Now().UnixNano()))
	if err := os.WriteFile(file, []byte(svg), 0o644); err != nil {
		return nil, err
	}
	defer os.Remove(file)
	name := a.Name
	if name == "" {
		name = "QR " + a.Text
		if r := []rune(name); len(r) > 40 {
			name = string(r[:40]) + "…"
		}
	}
	st := &styleArgs{Layer: a.Layer, Page: a.Page}
	var info corel.ShapeInfo
	err = d.S.Run(ctx, func(c *corel.Ctx) error {
		return withTarget(c, st, "create_qr_code", func(doc, layer *com.Dispatch, f geom.Frame) error {
			if _, err := doc.Call("ClearSelection"); err != nil {
				return err
			}
			opts, err := c.App.CallObj("CreateStructImportOptions")
			if err != nil {
				return err
			}
			res, err := layer.Method("ImportEx", file, 0, opts)
			if err != nil {
				return fmt.Errorf("QR import: %w", err)
			}
			if flt, ok := res.(*com.Dispatch); ok && flt != nil {
				if _, err := flt.Method("Finish"); err != nil {
					return fmt.Errorf("QR import: %w", err)
				}
			}
			sr, err := doc.GetObj("SelectionRange")
			if err != nil {
				return err
			}
			list := rangeList(sr)
			if len(list) == 0 {
				return errors.New("QR import produced nothing")
			}
			var shape *com.Dispatch
			if len(list) == 1 {
				shape = list[0]
				if t, _ := shape.GetInt("Type"); t == 7 {
					ug, err := shape.CallObj("UngroupAllEx")
					if err != nil {
						return err
					}
					list = rangeList(ug)
					shape = nil
				}
			}
			if shape == nil {
				r, err := newRange(c, list)
				if err != nil {
					return err
				}
				if len(list) == 1 {
					shape = list[0]
				} else if shape, err = r.CallObj("Combine"); err != nil {
					return err
				}
			}
			// exact size: the quiet zone is empty, so scale the dark modules
			darkW := float64(code.Size) * module
			w, h := darkW, darkW
			if err := resize(shape, f, &w, &h, false, "top-left"); err != nil {
				return err
			}
			// position: the anchor refers to the whole code incl. the quiet zone
			fr, err := anchorFrac(a.Anchor)
			if err != nil {
				return err
			}
			x0 := a.X - fr[0]*a.Size + float64(quiet)*module
			y0 := a.Y - fr[1]*a.Size + float64(quiet)*module
			if err := placeAt(shape, f, x0, y0, "top-left"); err != nil {
				return err
			}
			if err := c.SetFill(shape, col); err != nil {
				return err
			}
			none := colors.Color{Model: colors.None}
			if err := c.SetOutline(shape, &none, nil); err != nil {
				return err
			}
			_ = shape.Put("Name", name)
			info, err = c.DescribeShape(shape, f, "", 0)
			return err
		})
	})
	if err != nil {
		return nil, err
	}
	return mcp.JSONResult(fmt.Sprintf("QR code created (id %d): version %d, level %s, %d×%d modules + quiet zone %d, module %.3f mm.",
		info.ID, code.Version, "LMQH"[lvl:lvl+1], code.Size, code.Size, quiet, module), info), nil
}

