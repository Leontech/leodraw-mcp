func shapeBoolean(ctx context.Context, d *Deps, a *booleanArgs) (*mcp.Result, error) {
	var info corel.ShapeInfo
	var extra []corel.ShapeInfo
	err := d.S.Run(ctx, func(c *corel.Ctx) error {
		return withPage(c, a.Page, "shape_boolean", func(p *pageCtx) error {
			sr, list, err := p.shapes(&a.targetArgs)
			if err != nil {
				return err
			}
			switch a.Op {
			case "weld", "intersect":
				if len(list) < 2 {
					return errors.New(a.Op + " needs at least 2 shapes")
				}
				keep := a.Keep != nil && *a.Keep
				method := map[string]string{"weld": "Weld", "intersect": "Intersect"}[a.Op]
				res := list[0]
				for i, s := range list[1:] {
					// the intermediate result is never kept, the first original only with keep
					n, err := s.CallObj(method, res, keep, keep && i == 0)
					if err != nil {
						return err
					}
					if n == nil {
						return fmt.Errorf("%s gave no result (do the shapes overlap?)", a.Op)
					}
					res = n
				}
				info, err = c.DescribeShape(res, p.f, "", 0)
				return err
			case "trim":
				if a.TargetID == 0 {
					return errors.New("trim needs target_id (the shape to cut)")
				}
				target, err := corel.FindShape(p.page, a.TargetID)
				if err != nil {
					return err
				}
				keep := a.Keep == nil || *a.Keep
				for _, s := range list {
					if id, _ := s.GetInt("StaticID"); id == a.TargetID {
						continue
					}
					n, err := s.CallObj("Trim", target, keep, false)
					if err != nil {
						return err
					}
					if n != nil {
						target = n
					}
				}
				info, err = c.DescribeShape(target, p.f, "", 0)
				return err
			case "simplify":
				if len(list) < 2 {
					return errors.New("simplify needs at least 2 shapes")
				}
				// every shape is trimmed by the shapes lying in front of it (smaller ZOrder)
				z := make([]int64, len(list))
				for i, s := range list {
					z[i], _ = s.GetInt("ZOrder")
				}
				out := make([]*com.Dispatch, len(list))
				copy(out, list)
				for i := range out {
					for j := range list {
						if j == i || z[j] >= z[i] {
							continue
						}
						if n, err := list[j].CallObj("Trim", out[i], true, false); err == nil && n != nil {
							out[i] = n
						}
					}
				}
				_ = sr
				extra = p.describe(out)
				if len(extra) > 0 {
					info = extra[0]
				}
				return nil
			}
			return fmt.Errorf("unknown op %q", a.Op)
		})
	})
	if err != nil {
		return nil, err
	}
	if len(extra) > 1 {
		return shapesResult(fmt.Sprintf("%s done, %d shape(s).", a.Op, len(extra)), extra), nil
	}
	return mcp.JSONResult(fmt.Sprintf("%s done – result id %d.", a.Op, info.ID), info), nil
}

