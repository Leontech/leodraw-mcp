func offsetPath(ctx context.Context, d *Deps, a *offsetArgs) (*mcp.Result, error) {
	if a.Distance == 0 {
		return nil, errors.New("distance must not be 0")
	}
	corners := map[string]int{"": 2, "round": 2, "miter": 5, "bevel": 0}
	cn, ok := corners[a.Corners]
	if !ok {
		return nil, fmt.Errorf("unknown corners %q", a.Corners)
	}
	if a.Steps == 0 {
		a.Steps = 1
	}
	outCol := colors.Color{Model: colors.RGB}
	if a.Outline != "" {
		var err error
		if outCol, err = colors.Parse(a.Outline); err != nil {
			return nil, err
		}
	}
	keep := a.Keep == nil || *a.Keep
	var infos []corel.ShapeInfo
	err := d.S.Run(ctx, func(c *corel.Ctx) error {
		return withPage(c, a.Page, "offset_path", func(p *pageCtx) error {
			_, list, err := p.shapes(&a.targetArgs)
			if err != nil {
				return err
			}
			dir := 1 // cdrContourOutside
			if a.Distance < 0 {
				dir = 0 // inside
			}
			black, err := c.NewColor(colors.Color{Model: colors.RGB})
			if err != nil {
				return err
			}
			var made []*com.Dispatch
			for _, s := range list {
				// Direction, Offset, Steps, BlendType, OutlineColor, FillColor, FillColor2,
				// SpacingAccel, ColorAccel, EndCapType, CornerType, MiterLimit
				eff, err := s.CallObj("CreateContour", dir, math.Abs(a.Distance), a.Steps, 0, black, black, black, 0, 0, 1, cn, 15.0)
				if err != nil {
					return fmt.Errorf("contour: %w", err)
				}
				parts, err := eff.CallObj("Separate")
				if err != nil {
					return fmt.Errorf("contour separate: %w", err)
				}
				sid, _ := s.GetInt("StaticID")
				for _, part := range rangeList(parts) {
					if id, _ := part.GetInt("StaticID"); id == sid {
						continue
					}
					if t, _ := part.GetInt("Type"); t == 7 {
						if ug, err := part.CallObj("UngroupAllEx"); err == nil {
							made = append(made, rangeList(ug)...)
							continue
						}
					}
					made = append(made, part)
				}
				if !keep {
					if _, err := s.Call("Delete"); err != nil {
						return err
					}
				}
			}
			hair := hairlineMM
			for _, m := range made {
				_ = c.SetFill(m, colors.Color{Model: colors.None})
				_ = c.SetOutline(m, &outCol, &hair)
			}
			infos = p.describe(made)
			return nil
		})
	})
	if err != nil {
		return nil, err
	}
	return shapesResult(fmt.Sprintf("Created %d offset curve(s).", len(infos)), infos), nil
}

