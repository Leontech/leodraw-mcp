func traceBitmap(ctx context.Context, d *Deps, a *traceArgs) (*mcp.Result, error) {
	types := map[string]int{"line_art": 1, "": 2, "logo": 2, "detailed_logo": 3, "clipart": 4, "low_quality": 5,
		"high_quality": 6, "technical": 7, "line_drawing": 8}
	tt, ok := types[a.Type]
	if !ok {
		return nil, fmt.Errorf("unknown type %q", a.Type)
	}
	smooth, detail := 50, 50
	if a.Smoothing != nil {
		smooth = *a.Smoothing
	}
	if a.Detail != nil {
		detail = *a.Detail
	}
	removeBg := a.RemoveBg == nil || *a.RemoveBg
	var infos []corel.ShapeInfo
	traceInfo := ""
	err := d.S.Run(ctx, func(c *corel.Ctx) error {
		return withPage(c, a.Page, "trace_bitmap", func(p *pageCtx) error {
			s, err := corel.FindShape(p.page, a.ID)
			if err != nil {
				return err
			}
			if t, _ := s.GetInt("Type"); t != 5 {
				return fmt.Errorf("shape %d is not a bitmap", a.ID)
			}
			bmp, err := s.GetObj("Bitmap")
			if err != nil {
				return err
			}
			colorMode := 5 // RGB
			if a.Colors == 2 {
				colorMode = 8 // black and white
			}
			// TraceType, Smoothing, DetailLevelPercent, ColorMode, PaletteID, ColorCount,
			// DeleteOriginalObject, RemoveBackground, RemoveEntireBackColor
			ts, err := bmp.CallObj("Trace", tt, int16(smooth), int16(detail), colorMode, 7, a.Colors, !a.KeepBitmap, removeBg, false)
			if err != nil {
				return fmt.Errorf("PowerTRACE: %w", err)
			}
			if a.Colors > 2 {
				_, _ = ts.Call("SetColorCount", a.Colors)
			}
			_ = ts.Put("RemoveOverlap", true)
			_ = ts.Put("MergeAdjacentObjects", false)
			if _, err := ts.Call("ApplyChanges"); err != nil {
				return fmt.Errorf("PowerTRACE: %w", err)
			}
			cc, _ := ts.GetInt("ColorCount")
			cv, _ := ts.GetInt("CurveCount")
			traceInfo = fmt.Sprintf("PowerTRACE: %d colour(s), %d curve(s).", cc, cv)
			res, err := ts.CallObj("Finish")
			if err != nil {
				return fmt.Errorf("PowerTRACE: %w", err)
			}
			list := rangeList(res)
			if len(list) > 1 {
				if r, err := newRange(c, list); err == nil {
					if g, err := r.CallObj("Group"); err == nil {
						_ = g.Put("Name", "trace")
						list = []*com.Dispatch{g}
					}
				}
			}
			infos = p.describe(list)
			return nil
		})
	})
	if err != nil {
		return nil, err
	}
	return shapesResult(fmt.Sprintf("Traced into %d object(s). %s", len(infos), traceInfo), infos), nil
}

